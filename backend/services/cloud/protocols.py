"""Structural interfaces shared by local diagnostics and cloud services."""
from typing import Protocol, Any


class HistoryRepository(Protocol):
    def begin(self, description: str, answers: list, **kwargs) -> dict: ...
    def append(self, run_id: str, event: dict) -> None: ...
    def finish(self, run_id: str, run: dict) -> None: ...
    def read(self, run_id: str) -> dict | None: ...
    def enquiry(self, enquiry_id: str) -> dict | None: ...
    def list_enquiries(self, limit: int = 50, offset: int = 0, email: str = "") -> list: ...


class KnowledgeRepository(Protocol):
    def snapshot(self, version: str | None = None) -> Any: ...
    def directory(self, dataset: str = "technical", version: str | None = None) -> Any: ...
    def artifact(self, version: str, path: str) -> Any: ...


class IngestionJobRepository(Protocol):
    def enqueue(self, filename: str, role: str, reference: dict) -> dict: ...
    def claim(self) -> dict | None: ...
    def status(self) -> dict: ...
